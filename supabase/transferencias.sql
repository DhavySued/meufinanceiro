-- Transferências entre DREs (ex: Dhavy → Reserva do Casal).
-- Um único registro aparece nas duas pontas: Conta a Pagar na origem e Conta a Receber no destino.
-- No consolidado (dashboard com os dois selecionados) a transferência é interna e não é contada.
-- Execute uma vez no SQL Editor do Supabase.

create table if not exists public.transferencias (
  id          bigint generated by default as identity primary key,
  mes_ref     text    not null,                 -- competência 'YYYY-MM'
  origem_id   bigint  not null references public.responsaveis(id) on delete cascade,
  destino_id  bigint  not null references public.responsaveis(id) on delete cascade,
  quinzena    int     not null default 2 check (quinzena in (1, 2)),
  descricao   text    not null default '',
  valor       numeric not null check (valor > 0),
  realizada   boolean not null default false,   -- check de "feita": vale para as duas pontas
  created_at  timestamptz not null default now(),
  check (origem_id <> destino_id)
);

create index if not exists transferencias_mes_ref_idx on public.transferencias (mes_ref);

-- Mesmo acesso das demais tabelas do app (chave publishable)
alter table public.transferencias enable row level security;
drop policy if exists "app acesso total" on public.transferencias;
create policy "app acesso total" on public.transferencias
  for all to anon, authenticated using (true) with check (true);
